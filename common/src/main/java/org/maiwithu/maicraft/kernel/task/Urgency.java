package org.maiwithu.maicraft.kernel.task;

/**
 * 生存需求有多急：多快必须处理。每个生存需求每刻按角色处境给出自己的急迫程度。
 *
 * <p>例：饿了但还能疾跑，找空当吃就行；饥饿值低到不能疾跑、不回血，要尽快吃；饿到掉血、快淹死、正往虚空掉，必须立刻处理。
 */
public enum Urgency {
    /** 找空当处理：例如饿了吃一口、天黑去睡。只在两个动作之间插进来。 */
    LATER,
    /** 尽快处理：不处理会持续受伤，例如被怪打、身上着火。正常干活时立刻插进来，但停下不安全时先把手上这一下做完。 */
    SOON,
    /** 立刻处理：现在不处理就会死，例如坠向虚空、氧气见底、被埋在方块里。打断一切。 */
    NOW
}
